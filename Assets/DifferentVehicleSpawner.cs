using System.Collections.Generic;
using UnityEngine;

public class DifferentVehicleSpawner : MonoBehaviour
{
    [SerializeField] List<GameObject> Vehicles = new List<GameObject>(12);

    [SerializeField] Transform SpawnPosition;
    GameObject SpawnedVehicle;

    private void Awake()
    {
        int RandomCar = Random.Range(0, Vehicles.Count);

        switch (RandomCar)
        {
            case 0:
                SpawnedVehicle = Instantiate(Vehicles[0], SpawnPosition.position, Quaternion.identity);  break;
            case 1:
                SpawnedVehicle = Instantiate(Vehicles[1], SpawnPosition.position, Quaternion.identity);  break;
            case 2:
                SpawnedVehicle = Instantiate(Vehicles[2], SpawnPosition.position, Quaternion.identity);  break;
            case 3:
                SpawnedVehicle = Instantiate(Vehicles[3], SpawnPosition.position, Quaternion.identity);  break;
            case 4:
                SpawnedVehicle = Instantiate(Vehicles[4], SpawnPosition.position, Quaternion.identity);  break;
            case 5:
                SpawnedVehicle = Instantiate(Vehicles[5], SpawnPosition.position, Quaternion.identity); break;
            case 6:
                SpawnedVehicle = Instantiate(Vehicles[6], SpawnPosition.position, Quaternion.identity); break;
            case 7:
                SpawnedVehicle = Instantiate(Vehicles[7], SpawnPosition.position, Quaternion.identity); break;
            case 8:
                SpawnedVehicle = Instantiate(Vehicles[8], SpawnPosition.position, Quaternion.identity); break;
            case 9:
                SpawnedVehicle = Instantiate(Vehicles[9], SpawnPosition.position, Quaternion.identity); break;
            case 10:
                SpawnedVehicle = Instantiate(Vehicles[10], SpawnPosition.position, Quaternion.identity); break;
            case 11:
                SpawnedVehicle = Instantiate(Vehicles[11], SpawnPosition.position, Quaternion.identity); break;
            default:
                Debug.Log("Other Number Generated by Random Function");
                break;
        }

        SpawnedVehicle.transform.SetParent(SpawnPosition);
    }
}
